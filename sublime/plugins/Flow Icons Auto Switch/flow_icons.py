import os

import sublime
import sublime_plugin

SETTINGS = "Flow Icons.sublime-settings"
PREFERENCES = "Preferences.sublime-settings"
PALETTES = ("Flow Dawn", "Flow Deep", "Flow Dim", "Flow You")
DEFAULT_PALETTE = "Flow Dawn"
DEFAULT_COLOR = "sky"
DEFAULT_ICONS_PACKAGE = "Flow Icons"
DEFAULT_INTERVAL = 2000
ON_CHANGE_KEY = "flow_icons"
PACKAGE = "Flow Icons Auto Switch"
GENERATED_HEADER = "// Generated by the Flow Icons Auto Switch plugin. Do not edit.\n"

# Bumped on load/unload so timers left over from a previous plugin generation
# stop themselves instead of stacking up on every reload.
_generation = 0


def _settings():
    return sublime.load_settings(SETTINGS)


def _palette():
    palette = _settings().get("palette", DEFAULT_PALETTE)
    if palette not in PALETTES:
        print("Flow Icons: unknown palette {0!r}, using {1!r}".format(palette, DEFAULT_PALETTE))
        return DEFAULT_PALETTE
    return palette


def ui_style():
    """Return "dark" or "light" for the resolved UI, or None if undetectable.

    theme.style is what Adaptive actually resolved to, so it is a better
    signal than system.style: it follows the color scheme even when the OS
    appearance disagrees. system.style is only a fallback.
    """
    info = sublime.ui_info()
    for key in ("theme", "color_scheme", "system"):
        style = info.get(key, {}).get("style")
        if style in ("dark", "light"):
            return style
    return None


def icon_theme(style, palette=None):
    if palette is None:
        palette = _palette()
    suffix = " (Light)" if style == "light" else ""
    return "{0}{1}.sublime-file-icons".format(palette, suffix)


def folder_texture(style, palette=None, color=None, expanded=False):
    """Name of the folder PNG for a palette/style, without extension.

    Flow Dawn's dark set ships unprefixed; everything else is prefixed with
    the palette (and "_light" for light variants).
    """
    if palette is None:
        palette = _palette()
    if color is None:
        color = _settings().get("folder_color", DEFAULT_COLOR) or DEFAULT_COLOR
    suffix = "_open" if expanded else ""

    if palette == "Flow Dawn" and style != "light":
        return "file_type_folder_{0}{1}".format(color, suffix)

    slug = palette.split(" ")[-1].lower()
    light = "_light" if style == "light" else ""
    return "file_type_flow_{0}{1}_folder_{2}{3}".format(slug, light, color, suffix)


def _theme_override(style):
    """Theme rules pinning the folder icons to the current palette/style.

    Written into this package rather than Packages/User so the user's own
    theme customizations are never touched. layer0.tint is reset to white
    because Adaptive tints folder icons black on light UIs and the tint
    multiplies, which would wash the colors out.
    """
    package = _settings().get("icons_package", DEFAULT_ICONS_PACKAGE) or DEFAULT_ICONS_PACKAGE
    closed = folder_texture(style)
    opened = folder_texture(style, expanded=True)
    return (
        GENERATED_HEADER
        + '{\n'
        '    "rules":\n'
        '    [\n'
        '        {\n'
        '            "class": "icon_folder",\n'
        '            "layer0.texture": "%s/icons/%s.png",\n'
        '            "layer0.tint": "white",\n'
        '            "layer0.opacity": 1.0,\n'
        '            "content_margin": 8\n'
        '        },\n'
        '        {\n'
        '            "class": "icon_folder",\n'
        '            "parents": [{"class": "tree_row", "attributes": ["expanded"]}],\n'
        '            "layer0.texture": "%s/icons/%s.png"\n'
        '        }\n'
        '    ]\n'
        '}\n' % (package, closed, package, opened)
    )


def _sync_folder_icons(style):
    """Write the folder override for the active theme, dropping stale ones."""
    if not _settings().get("manage_folder_icons", True):
        return

    info = sublime.ui_info()
    theme = info.get("theme", {}).get("resolved_value")
    if not theme:
        return
    theme = os.path.basename(theme)

    directory = os.path.join(sublime.packages_path(), PACKAGE)
    if not os.path.isdir(directory):
        return

    for stale in os.listdir(directory):
        if stale.endswith(".sublime-theme") and stale != theme:
            try:
                os.remove(os.path.join(directory, stale))
            except OSError:
                pass

    contents = _theme_override(style)
    path = os.path.join(directory, theme)
    try:
        with open(path, "r") as handle:
            if handle.read() == contents:
                return
    except IOError:
        pass

    with open(path, "w") as handle:
        handle.write(contents)


def sync():
    """Point file_icon_theme and the folder icons at the current UI style."""
    style = ui_style()
    if style is None:
        return None

    _sync_folder_icons(style)

    wanted = icon_theme(style)
    preferences = sublime.load_settings(PREFERENCES)
    if preferences.get("file_icon_theme") == wanted:
        return wanted

    preferences.set("file_icon_theme", wanted)
    sublime.save_settings(PREFERENCES)
    print("Flow Icons: switched to {0}".format(wanted))
    return wanted


def _poll(generation):
    if generation != _generation:
        return
    if _settings().get("auto_switch", True):
        sync()
    try:
        interval = max(250, int(_settings().get("poll_interval", DEFAULT_INTERVAL)))
    except (TypeError, ValueError):
        interval = DEFAULT_INTERVAL
    sublime.set_timeout(lambda: _poll(generation), interval)


def plugin_loaded():
    global _generation
    _generation += 1
    generation = _generation

    settings = _settings()
    settings.clear_on_change(ON_CHANGE_KEY)
    settings.add_on_change(ON_CHANGE_KEY, sync)
    sublime.set_timeout(lambda: _poll(generation), 0)


def plugin_unloaded():
    global _generation
    _generation += 1
    _settings().clear_on_change(ON_CHANGE_KEY)


class FlowIconsSyncCommand(sublime_plugin.ApplicationCommand):
    def run(self):
        applied = sync()
        if applied is None:
            sublime.status_message("Flow Icons: could not detect the UI style")
        else:
            sublime.status_message("Flow Icons: {0}".format(applied))


class FlowIconsSelectPaletteCommand(sublime_plugin.WindowCommand):
    def run(self):
        current = _palette()
        style = ui_style() or "dark"
        items = []
        for palette in PALETTES:
            mark = " (current)" if palette == current else ""
            items.append([palette + mark, icon_theme(style, palette)])

        def on_done(index):
            if index == -1:
                return
            settings = _settings()
            settings.set("palette", PALETTES[index])
            sublime.save_settings(SETTINGS)
            sync()

        self.window.show_quick_panel(items, on_done)
